"""A guided tour of the data layer. Run with `make demo` (or locally with OMS_DSN/DATA_DIR set).

Every query below is expressed purely in business terms. The data behind it
lives in Postgres, Parquet, SQLite and a CSV feed, using three identifier
schemes and two weight conventions; none of that appears here.
"""

import textwrap

import pandas as pd

from semlayer import DataLayer, QueryError

pd.set_option("display.width", 160)
pd.set_option("display.max_columns", 12)
pd.set_option("display.float_format", lambda v: f"{v:,.4f}")

AS_OF = "2026-09-30"
QUARTER = ("2026-06-30", AS_OF)
dl = DataLayer.from_env()


def section(title: str) -> None:
    print(f"\n{'=' * 78}\n{title}\n{'=' * 78}")


def note(text: str) -> None:
    print(textwrap.fill(" ".join(text.split()), 78), end="\n\n")


def show(df: pd.DataFrame) -> None:
    text_cols = df.select_dtypes(include=["object", "string"]).columns
    print(df.fillna({c: "(none)" for c in text_cols}).to_string(index=False), end="\n\n")


section("0. The example data")
note("""
    Everything here is fictional and generated by src/semlayer/seed.py: three funds, each measured
    against a benchmark index, and 60 securities with month-end data from June to September 2026.
    Every security has one canonical id, S0001 to S0060, which the layer maps each store's own
    identifiers (SEDOL in the OMS, ISIN in the lake and vendor feed) onto.
""")
show(dl.query(
    metrics=["holding_count", "market_value"],
    dimensions=["fund.code", "fund.name", "benchmark.name"],
    as_of=AS_OF,
).df)
note("""
    A few things are planted in the data so the examples below always have something to show:
    S0001 Northwind Systems changes sector on 2026-08-15; S0003 Halcyon Pharma has its credit rating
    cut to high yield on 2026-09-10; UK_EQ buys a new listing the security master doesn't know yet;
    and GLB_EQ has two portfolio managers.
""")

section("1. Sector active weights for one fund")
note("""
    Active weight = the fund's weight minus the benchmark's weight. Positive means the fund holds
    more than the benchmark (overweight), negative means less (underweight).
""")
res = dl.query(
    metrics=["portfolio_weight", "benchmark_weight", "active_weight"],
    dimensions=["security.sector"],
    filters={"fund.code": "GLB_EQ"},
    as_of=AS_OF,
    order_by=["-active_weight"],
)
show(res.df)
unheld = ", ".join(res.df.loc[res.df.portfolio_weight == 0, "security.sector"])
note(f"""
    {unheld}: the fund holds nothing there, but the sector still appears as an underweight because
    the layer keeps benchmark names the fund doesn't own.
""")

section("2. ...and what actually ran (explain)")
note("""
    The same query, showing the SQL sent to each store and the final SQL that combines the results.
    Note "weight_percent" / 100.0: the OMS stores weights in percent, the model uses fractions.
""")
print(res.explain())

section("3. Fund summary over the quarter")
note("""
    One row per fund per month-end. active_share: how different the fund is from its benchmark
    (0 = identical, 1 = no overlap). active_rating_score: credit quality versus the benchmark, in
    rating notches (positive = higher quality). active_esg_score and esg_coverage: the same idea for
    the separate ESG rating, and the share of the fund that has one.
""")
show(dl.query(
    metrics=["market_value", "holding_count", "active_share", "active_rating_score", "active_esg_score", "esg_coverage"],
    dimensions=["fund.code", "time.as_of_date"],
    date_range=QUARTER,
).df)

section("4. Point-in-time: Northwind Systems (S0001) changes sector on 2026-08-15")
note("""
    Sectors change over time, so the layer uses the sector that was valid on each date, not
    today's. Northwind's weight moves from Information Technology to Communication Services
    between the July and August month-ends.
""")
show(dl.query(
    metrics=["portfolio_weight"],
    dimensions=["time.as_of_date", "security.id", "security.name", "security.sector"],
    filters={"fund.code": "GLB_EQ", "security.id": "S0001"},
    date_range=QUARTER,
    order_by=["time.as_of_date"],
).df)

section("5. Credit rating: Halcyon Pharma (S0003) is cut to high yield on 2026-09-10")
note("""
    BBB- is the lowest investment-grade rating and BB+ the highest high-yield one, so this cut moves
    Halcyon from investment grade to high yield (a "fallen angel"). The rating is point-in-time too.
""")
halcyon = dl.query(
    metrics=["portfolio_weight", "benchmark_weight"],
    dimensions=["time.as_of_date", "security.id", "security.name", "security.rating", "security.rating_grade"],
    filters={"fund.code": "GLB_EQ", "security.id": "S0003"},
    date_range=("2026-08-31", AS_OF),
).df
show(halcyon)
note("""
    GLB_EQ doesn't hold Halcyon (portfolio_weight 0); it appears because it is part of the
    benchmark. Here is the fund and benchmark split by grade on the same two dates:
""")
show(dl.query(
    metrics=["portfolio_weight", "benchmark_weight", "active_weight"],
    dimensions=["time.as_of_date", "security.rating_grade"],
    filters={"fund.code": "GLB_EQ"},
    date_range=("2026-08-31", AS_OF),
).df)
note(f"""
    Halcyon's {halcyon.benchmark_weight.iloc[-1]:.1%} of the benchmark moved from Investment grade
    to High yield (other securities' ratings also changed, so the totals move by a bit more).
    A grade of (none) means the security has no credit rating. ESG ratings are separate:
    security.esg_rating.
""")

section("6. Guard rails: queries that would return wrong numbers are refused")
note("""
    Each of these would produce a plausible-looking but wrong number, so the layer refuses it and
    says how to fix the query.
""")
for desc, kwargs in [
    ("weights summed across funds (3 funds, each 100%, would add up to 300%)",
     dict(metrics=["portfolio_weight"], dimensions=["security.sector"], as_of=AS_OF)),
    ("weights by portfolio manager (GLB_EQ has two, so it would count twice)",
     dict(metrics=["portfolio_weight"], dimensions=["fund.code", "fund.portfolio_manager"], as_of=AS_OF)),
    ("market value summed over four month-ends (four times the real value)",
     dict(metrics=["market_value"], dimensions=["fund.code"], date_range=QUARTER)),
]:
    try:
        dl.query(**kwargs)
    except QueryError as e:
        print(f"- {desc}:\n    {e}\n")

section("7. Data quality surfaced, not hidden")
note("""
    On 2026-09-30 UK_EQ holds a new listing whose SEDOL isn't in the security master yet. Its
    weight stays in the totals (so they still add up to 100%), its region is (none), and the
    layer reports it as a warning rather than silently dropping it.
""")
res = dl.query(metrics=["portfolio_weight"], dimensions=["security.region"], filters={"fund.code": "UK_EQ"}, as_of=AS_OF)
show(res.df)
for w in res.plan.warnings:
    print("WARNING:", w)
